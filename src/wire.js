// 侧视整体折线集（上轮廓 + 底线 + 细节 + 车轮圆）——也是撞毁碎线数据源
export function sideProfile(type) {
  const out = [];
  const top = SIDE_TOP[type] || SIDE_TOP.sedan;
  out.push(top);
  const x0 = top[0][0], x1 = top[top.length - 1][0];
  out.push([[x0, top[0][1]], [x0, 0.06], [x1, 0.06], [x1, top[top.length - 1][1]]]);
  for (const d of (SIDE_DETAIL[type] || [])) out.push(d);
  for (const w of (WHEELS[type] || [])) {
    const pts = [];
    for (let i = 0; i <= 12; i++) {
      const a = (i / 12) * Math.PI * 2;
      pts.push([w.x + Math.cos(a) * w.r, w.r + Math.sin(a) * w.r * 0.96]);
    }
    out.push(pts);
  }
  return out;
}

